"""M4: the cues for Act 1's code-drawn overlays (brief: "HTML/canvas, captured frame by frame with Puppeteer ...
Generic UI only"), from the timing map and the word alignment. After Not Yet's overlay_cues.py.

Two kinds, one file (overlays/cues.json), all times song seconds:
  overlay   drawn over the picture by overlays/overlay.html (overlays/render.mjs), composited in the edit:
            S03 the phone-line waveform spiking on "recorded"; S06 the day counter 30 -> 0; S07-S08 the running
            total in $0.24 steps, landing on $20,000,000; S13 the "0 results" caption; S35 the counter to 144,926
  screens   in-world screens drawn by overlays/screens.html (overlays/screens.mjs) to image sequences that the
            Blender set maps onto their surfaces: S10 the lobby screen flashing BLACKMAIL; S16 the pawn shop's LED
            countdown from 48:00:00; S20 the lobby's traffic chart, dipping and bouncing back; S30 the LED ticker band

Usage: .venv/bin/python -I scripts/overlay_cues.py
"""
import json
import sys
from pathlib import Path

import librosa
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from song import stem  # noqa: E402

TM = json.loads(Path("timing/timing_map.json").read_text())
WORDS = json.loads(Path("timing/words.json").read_text())["lines"]
BOOK = json.loads(Path("config/bookends.json").read_text())
PRE = sum(BOOK["preroll"].values())
SHOT = {s["id"]: (s["t"], s["end"]) for s in TM["shots"] if s["t"] is not None}


def word(line_id, prefix):
    ln = next(l for l in WORDS if l["id"] == line_id)
    return next(w for w in ln["words"] if w["w"].lower().startswith(prefix))


def beats(a, b, sub=1):
    """Beats (sub=2: eighth notes) between a and b."""
    bs = TM["beats"]
    out = []
    for k in range(len(bs) - 1):
        for j in range(sub):
            t = bs[k] + (bs[k + 1] - bs[k]) * j / sub
            if a <= t < b:
                out.append(round(t, 3))
    return out


def waveform(a, b, rate=200):
    """The lead stem (the phone-line vocal) as min/max pairs at `rate` per second, normalised to the span's peak."""
    y, sr = librosa.load(stem("Lead Vocals"), sr=16000, mono=True, offset=a, duration=b - a)
    hop = sr // rate
    n = len(y) // hop
    blk = y[:n * hop].reshape(n, hop)
    pk = np.abs(y).max() + 1e-9
    return {"from": a, "rate": rate, "min": np.round(blk.min(1) / pk, 3).tolist(), "max": np.round(blk.max(1) / pk, 3).tolist()}


def main():
    rec = word("L02", "recorded")
    s03, s06, s07, s08, s13, s35 = (SHOT[k] for k in ("S03", "S06", "S07", "S08", "S13", "S35"))
    s10, s16, s20, s30 = (SHOT[k] for k in ("S10", "S16", "S20", "S30"))
    dark, bounced = word("L21", "dark"), word("L22", "bounced")
    beat_in = [b for a, b in TM["drum_dropouts"] if b < 12][-1]
    cues = {
        "_doc": "Generated by scripts/overlay_cues.py; do not edit. Song seconds.",
        "fps": TM["fps"], "pre": PRE,
        "palette": {"ui": "#f1f4ee", "dim": "#8d97a6", "panel": "rgba(8,10,14,0.72)", "rec": "#ff2a2a",
                    "led": "#ff2a2a", "screen": "#7fe0ff", "ticker": "#55ff7a", "corporate": "#cfe6ff"},
        "overlay": [
            # S03: on from the shot's start until the beat comes in and the camera pulls back
            {"kind": "wave", "shot": "S03", "on": s03[0], "off": beat_in + 0.8, "spike": [rec["start"], rec["end"]],
             "data": waveform(s03[0] - 2.0, beat_in + 1.0)},
            {"kind": "days", "shot": "S06", "on": s06[0], "off": s06[1], "from": 30, "to": 0,
             "steps": beats(s06[0] + 0.1, s06[1] - 0.25, 4)},
            {"kind": "total", "shot": "S07-S08", "on": s07[0], "off": s08[1], "step": 0.24,
             "land": round(s08[0] + 1.0, 3), "value": 20_000_000},
            {"kind": "results", "shot": "S13", "on": s13[0], "off": s13[1], "query": "threat",
             "typed": round(s13[0] + 1.2, 3), "result": round(s13[0] + 1.8, 3)},
            {"kind": "counter", "shot": "S35", "on": s35[0], "off": s35[1], "value": 144_926, "land": round(s35[1] - 0.7, 3)},
        ],
        "screens": {
            "lobby_blackmail": {"size": [1600, 680], "shot": "S10", "from": s10[0], "to": s10[1],
                                "flash": beats(s10[0], s10[1], 2)},
            "lobby_traffic": {"size": [1600, 680], "shot": "S20", "from": s20[0], "to": s20[1],
                              "dip": [dark["start"], dark["end"] + 0.6], "bounce": [bounced["start"], bounced["end"] + 0.2],
                              "bounces": beats(s20[0], s20[1])},
            "pawn_led": {"size": [1040, 240], "shot": "S16", "from": s16[0] - 0.5, "to": s16[1] + 0.5,
                         "count": [s16[0], s16[1]], "hours": 48},
            # a seamless loop, mapped cyclic onto the band from S30 on; slow, so motion blur doesn't double the dots
            "ticker": {"size": [4000, 160], "shot": "S30", "from": s30[0], "to": s30[0] + 24.0, "loop": True,
                       "text": "IPO  ▲  OPENING BELL  ▲  UP  UP  UP  ▲  NEW MANAGEMENT  ▲  "
                               "USER CONTENT NOT INCLUDED  ▲  "},
        },
    }
    Path("overlays").mkdir(exist_ok=True)
    Path("overlays/cues.json").write_text(json.dumps(cues, indent=1) + "\n")
    print("overlays/cues.json:", ", ".join(o["kind"] for o in cues["overlay"]), "|", ", ".join(cues["screens"]))


if __name__ == "__main__":
    main()
